import AppHeader from "@/components/app-header/app-header";
import CartDrawer from "@/components/cart/cartdrawer/cartdrawer";
import FloatingCartButton from "@/components/floatingcartbutton/floatingcartbutton";
import { I18nProvider } from "@/context/diccontext";
import type { Metadata } from "next";

import { PageAnimatePresence } from "@/components/animation/pageanimatepresence/pageanimatepresence";
import { getDictionary } from "@/lib/dictionaries";
import { isLanguage } from "@/types/index";
import { notFound } from "next/navigation";

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function LangLayout({
  children,
  params,
}: {
  children: React.ReactNode;
  params: Promise<{ lang: string }>;
}) {
  const { lang } = await params;

  if (!isLanguage(lang)) {
    notFound();
  }

  const dict = await getDictionary(lang);

  return (
    <I18nProvider lang={lang} dictionary={dict}>
      <PageAnimatePresence>
        <AppHeader />
        <CartDrawer />
        <FloatingCartButton />
        {children}
      </PageAnimatePresence>
    </I18nProvider>
  );
}


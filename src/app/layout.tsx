import "./globals.css";
import type { Metadata } from "next";
import { DynaPuff } from "next/font/google";
import { CartProvider } from "@/context/cartcontext";
import { CategoryService } from "@/services/category/service";

const geistSans = DynaPuff({
  subsets: ["latin"],
  weight: "400",
});

export const dynamic = "force-dynamic";

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export const viewport = {
  width: "device-width",
  initialScale: 1,
};

const [menu] = await Promise.all([CategoryService.getMenu()]);

const allProducts = menu.flatMap((category) => category.products);

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html className={`${geistSans.className} min-h-full flex flex-col`}>
      <body>
        <CartProvider products={allProducts}>{children} </CartProvider>
      </body>
    </html>
  );
}
